"""AI Analysis page — LLM-powered market analysis and insights.

Integrates with local LLM (llama-server) for generating market
commentary, trade ideas, and portfolio reviews. All LLM calls are
mockable for testing.
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


# =============================================================================
# LLM integration helpers
# =============================================================================


def _call_llm(
    prompt: str,
    model: str = "default",
    max_tokens: int = 1024,
    temperature: float = 0.7,
) -> str:
    """Call local LLM endpoint for analysis.

    This is a thin wrapper — actual HTTP call should be mocked in tests.

    Returns
    -------
    Generated text from the LLM, or error message.
    """
    try:
        import requests
        resp = requests.post(
            "http://localhost:8080/v1/chat/completions",
            json={
                "model": model,
                "messages": [{"role": "user", "content": prompt}],
                "max_tokens": max_tokens,
                "temperature": temperature,
            },
            timeout=30,
        )
        resp.raise_for_status()
        data = resp.json()
        return data["choices"][0]["message"]["content"]
    except Exception as exc:
        logger.warning("LLM call failed: %s", exc)
        return f"LLM unavailable: {exc}"


ANALYSIS_TYPES = {
    "Market Overview": "Provide a brief market overview covering major indices, sectors, and themes.",
    "Trade Ideas": "Suggest 3 trade ideas with entry/exit levels and risk management.",
    "Portfolio Review": "Review the portfolio allocation and suggest improvements.",
    "Risk Assessment": "Assess current market risks and potential catalysts.",
    "Sector Analysis": "Analyze sector rotation and relative strength.",
}


# =============================================================================
# Dashboard render
# =============================================================================


def render() -> None:
    """Render the AI Analysis page."""
    import streamlit as st

    from quant_tools.dashboard.core.page_help import render_page_help

    st.header("AI Analysis")

    render_page_help("ai_analysis")
    st.markdown(
        "LLM-powered market analysis using your local model. "
        "Requires llama-server running on localhost:8080."
    )

    # ── Sidebar ──
    with st.sidebar:
        st.subheader("Analysis Settings")
        analysis_type = st.selectbox(
            "Analysis Type",
            list(ANALYSIS_TYPES.keys()),
            key="ai_analysis_type",
        )
        temperature = st.slider(
            "Temperature",
            min_value=0.0,
            max_value=1.5,
            value=0.7,
            step=0.1,
            key="ai_temperature",
        )
        max_tokens = st.slider(
            "Max Tokens",
            min_value=256,
            max_value=4096,
            value=1024,
            step=256,
            key="ai_max_tokens",
        )

    # ── Main content ──
    st.subheader(analysis_type)

    col1, col2 = st.columns([3, 1])
    with col1:
        custom_prompt = st.text_area(
            "Custom prompt (optional)",
            value="",
            key="ai_custom_prompt",
            placeholder="Override the default prompt...",
        )
    with col2:
        generate = st.button("Generate Analysis", key="ai_generate")

    if generate:
        prompt = custom_prompt or ANALYSIS_TYPES.get(analysis_type, "")
        with st.spinner("Generating analysis..."):
            result = _call_llm(
                prompt=prompt,
                temperature=temperature,
                max_tokens=max_tokens,
            )
        st.markdown("---")
        st.markdown(result)
    else:
        st.info(
            "Click **Generate Analysis** to run the selected analysis type. "
            "You can also enter a custom prompt."
        )

    st.divider()
    st.caption(
        "Analysis generated by local LLM. Not financial advice. "
        "Verify all suggestions independently."
    )
